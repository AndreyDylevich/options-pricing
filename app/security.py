"""Проверка административного токена на эндпоинтах, меняющих состояние.
Ничего не считает — решает, пускать запрос или отказать.
"""

import secrets

from fastapi import Header, HTTPException, status

from app.config import settings

# Сервер слушает 127.0.0.1, и снаружи до него не дотянуться — но этого
# мало. Любая страница, открытая в браузере пользователя, может послать
#
#     fetch("http://127.0.0.1:8000/api/instruments/sync", {method: "POST"})
#
# Это «простой запрос»: своих заголовков нет, тип содержимого обычный,
# поэтому предварительной проверки CORS браузер не делает и запрос уходит.
# Ответ чужая страница не прочитает, а побочное действие уже случится —
# полсотни обращений к Yahoo от нашего имени.
#
# Защита двухслойная, и первый слой важнее. Свой заголовок: чтобы отправить
# X-Admin-Token из другого источника, браузер обязан сначала спросить
# разрешения запросом OPTIONS, а мы на него не отвечаем — значит основной
# запрос не уйдёт вовсе, даже с угаданным токеном. Значение токена:
# работает там, где браузера нет — curl, чужой процесс на машине,
# случайно открытый наружу порт.
HEADER_NAME = "X-Admin-Token"

# Случайный токен на время жизни процесса. Пересоздаётся при каждом
# запуске, поэтому в репозиторий попасть не может по построению.
_GENERATED = secrets.token_urlsafe(32)


# Токен берётся из ADMIN_TOKEN в .env, а если его там нет — сгенерированный
# при старте. Так защита действует без настройки, ценой того, что после
# перезапуска прежний токен недействителен; для локального приложения это
# скорее плюс.
def admin_token() -> str:
    return settings.admin_token or _GENERATED


def require_admin_token(
    x_admin_token: str | None = Header(default=None, alias=HEADER_NAME),
) -> None:
    if x_admin_token is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Нужен заголовок {HEADER_NAME}",
        )

    # compare_digest, а не ==: обычное сравнение строк выходит на первом
    # несовпавшем символе, и по времени ответа токен подбирается
    # посимвольно. Здесь это почти теория, но правило дешёвое.
    if not secrets.compare_digest(x_admin_token, admin_token()):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Неверный административный токен",
        )
