"""Защита эндпоинтов, меняющих состояние.

Сервер слушает 127.0.0.1, и снаружи до него не дотянуться — но этого мало.
Любая страница, открытая в браузере пользователя, может послать

    fetch("http://127.0.0.1:8000/api/instruments/sync", {method: "POST"})

Это «простой запрос»: своих заголовков нет, тип содержимого обычный,
поэтому предварительной проверки CORS браузер не делает и запрос уходит.
Ответ чужая страница не прочитает, а побочное действие уже случится —
полсотни обращений к Yahoo от нашего имени, а раньше ещё и удаление
справочника через `replace=true`.

Защита двухслойная, и первый слой важнее второго:

1. **Свой заголовок.** Чтобы отправить `X-Admin-Token` из другого
   источника, браузер обязан сначала спросить разрешения запросом
   OPTIONS. Мы на него не отвечаем, значит основной запрос не уйдёт
   вовсе — даже с угаданным токеном.
2. **Значение токена.** Работает там, где браузера нет: curl, чужой
   процесс на той же машине, случайно открытый наружу порт.

Токен берётся из `ADMIN_TOKEN` в `.env`, а если его там нет —
генерируется случайный при старте. Так защита действует без настройки,
ценой того, что после перезапуска старый токен недействителен. Для
локального приложения это скорее плюс.
"""

import secrets

from fastapi import Header, HTTPException, status

from app.config import settings

HEADER_NAME = "X-Admin-Token"

# Случайный токен на время жизни процесса. Пересоздаётся при каждом
# запуске, поэтому в репозиторий попасть не может по построению.
_GENERATED = secrets.token_urlsafe(32)


def admin_token() -> str:
    """Действующий токен: из настроек, иначе сгенерированный при старте."""
    return settings.admin_token or _GENERATED


def require_admin_token(
    x_admin_token: str | None = Header(default=None, alias=HEADER_NAME),
) -> None:
    """Зависимость FastAPI: пускать только со знанием токена.

    Сравнение через `compare_digest`, а не `==`: обычное сравнение строк
    выходит на первом несовпавшем символе, и по времени ответа токен
    подбирается посимвольно. Здесь это почти теория, но правило дешёвое.
    """
    if x_admin_token is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Нужен заголовок {HEADER_NAME}",
        )

    if not secrets.compare_digest(x_admin_token, admin_token()):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Неверный административный токен",
        )
