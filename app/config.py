"""Настройки приложения: адрес базы, сроки кэша и хранения, лимиты нагрузки,
административный токен. Читаются из .env, значения по умолчанию здесь же.
"""

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    database_url: str = "postgresql+asyncpg://postgres@localhost:5432/pricing"
    default_risk_free_rate: float = 0.042
    market_cache_ttl_minutes: int = 15

    # Ограничение частоты запросов с одного адреса. Общий лимит щадящий:
    # открытие страницы само по себе делает несколько запросов подряд.
    rate_limit: str = "120/minute"

    # Отдельный, жёсткий — на расчётные эндпоинты. Считают они куда
    # дороже, чем отдают данные: Монте-Карло с пятью миллионами путей
    # запускает симуляцию двенадцать раз, по одной на цену и одиннадцать
    # на численные греки.
    pricing_rate_limit: str = "30/minute"

    # Сколько расчётов считать одновременно. Ограничения частоты для
    # этого мало: лимит «30 в минуту» не мешает всем тридцати прийти в
    # одну секунду, а каждый тяжёлый расчёт держит до 200 МБ. Без потолка
    # FastAPI отдал бы под них сорок потоков — восемь гигабайт пика.
    max_concurrent_pricing: int = 4

    # Токен для эндпоинтов, меняющих состояние. Пустой означает «сгенерить
    # случайный при старте»: защита работает без настройки, но после
    # перезапуска прежний токен недействителен. Задавать явно стоит
    # только если дёргать /sync из скриптов, см. app/security.py.
    admin_token: str = ""

    # Сколько дней держать историю расчётов. Наружу она не отдаётся,
    # смотрят её прямо в PostgreSQL, и хранить там месяцы отладочных
    # прогонов незачем — таблица растёт от каждого нажатия «Рассчитать»
    # и от каждого прогона тестов.
    calculation_retention_days: int = 3

    # Сколько страйков должно иметь живые котировки, чтобы бумага попала в
    # список. Считается по обеим сторонам месячной цепочки. Ниже двадцати
    # улыбку волатильности строить не по чему.
    min_quoted_strikes: int = 20


settings = Settings()
